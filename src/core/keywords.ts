const UPPER = new Set(KEYWORDS.map((k) => k.toUpperCase()));

/** True for built-in keywords/functions, including any `_`-prefixed name. */
export function isKeyword(name: string): boolean {
  const upper = name.toUpperCase();
  const bare = upper.replace(/~?(?:%%|&&|##|[%&!#`])$|\$$/, "");
  if (bare.startsWith("_")) return true;
  return UPPER.has(upper) || UPPER.has(bare) || UPPER.has(bare.replace(/^_/, ""));
}
